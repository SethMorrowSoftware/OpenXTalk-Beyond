"""The "Install build tools" steps of the container builds: a failed
apt-get install runs again after a fresh apt-get update and a wait, three
passes in all. Acquire::Retries does not retry a 404, which a mirror in
the middle of a sync gives (security.ubuntu.com's perl, 10 Nov 2026, #383
and #449). The steps' own loop is run here with a fake apt-get and sleep.

And the name servers of the package steps (#476): on 11 Nov 2026 the hosted
runners' name servers stopped answering for Ubuntu's package servers, on
the runners and in the job containers, while two public name servers kept
answering. The loop, and tools/ci/apt-name-servers.sh for the steps that
run on the runner, add those two after the machine's own when a server of
the apt sources does not resolve; both are run here with a fake getent
that resolves as the runners did that day. Every step of every workflow
that installs packages is held to it.

  python3 -m unittest discover -s tools/ci/tests
"""

import os
import re
import shutil
import subprocess
import tempfile
import unittest

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
WORKFLOWS = os.path.join(HERE, '..', '..', '..', '.github', 'workflows')
ACTIONS = os.path.join(HERE, '..', '..', '..', '.github', 'actions')
SCRIPT = os.path.join(HERE, '..', 'apt-name-servers.sh')
FILES = ('web.yml', 'web-ide.yml', 'build-linux.yml', 'android-engine.yml')

# apt-get that fails "install" the number of times in $FAILS, counting in
# $STATE, and logs every call
FAKE_APT = '''#!/bin/bash
echo "$*" >> "$STATE/calls"
case " $* " in
  *" install "*)
    n=$(cat "$STATE/installs" 2>/dev/null || echo 0)
    echo $((n + 1)) > "$STATE/installs"
    if [ "$n" -lt "$FAILS" ]; then exit 100; fi ;;
esac
exit 0
'''


# getent as the hosted runners resolved on 11 Nov 2026 ($DNS is "down"):
# no name of Canonical's zones with the machine's own name servers, every
# name once /etc/resolv.conf also names the two public ones; logs every call
FAKE_GETENT = '''#!/bin/bash
echo "$*" >> "$STATE/lookups"
if [ "$DNS" = up ]; then exit 0; fi
case $2 in *.ubuntu.com|*.launchpadcontent.net) ;; *) exit 0 ;; esac
if grep -q '^nameserver 1\\.1\\.1\\.1$' "$RESOLV_CONF" &&
   grep -q '^nameserver 9\\.9\\.9\\.9$' "$RESOLV_CONF"; then exit 0; fi
exit 2
'''

SOURCES = ('deb http://archive.ubuntu.com/ubuntu/ jammy main restricted\n'
           'deb http://security.ubuntu.com/ubuntu/ jammy-security main restricted\n')

# A job container's /etc/resolv.conf, and a hosted runner's
RESOLV = ('# Generated by Docker Engine.\n\nnameserver 127.0.0.11\n'
          'search example.internal.cloudapp.net\noptions edns0 trust-ad ndots:0\n')
RESOLV_HOST = 'nameserver 127.0.0.53\noptions edns0 trust-ad\nsearch example.internal.cloudapp.net\n'
PUBLIC = ['1.1.1.1', '9.9.9.9']


def name_servers(text):
    return re.findall(r'^nameserver (\S+)$', text, re.M)


def loop(name):
    """The retry loop of the workflow's Install build tools step, as bash."""
    with open(os.path.join(WORKFLOWS, name), encoding='utf-8') as f:
        text = f.read()
    m = re.search(r'^( +)for pass in 1 2 3; do\n.*?^\1done\n', text, re.M | re.S)
    if not m:
        return None
    return '\n'.join(line[len(m.group(1)):] for line in m.group(0).splitlines()) + '\n'


# The steps run in Linux containers; the loop is run here only where bash
# runs the fake tools as programs (not on the Windows runner)
POSIX = unittest.skipUnless(os.name == 'posix' and shutil.which('bash'), 'the step runs in bash on Linux')


class Machine(unittest.TestCase):
    """A folder that stands for a machine: fake apt-get, sleep and getent,
    the apt sources and /etc/resolv.conf."""

    def machine(self, sources=None, resolv=RESOLV):
        state = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, state)
        bin_dir = os.path.join(state, 'bin')
        os.makedirs(bin_dir)
        for tool, body in (('apt-get', FAKE_APT), ('getent', FAKE_GETENT),
                           ('sleep', '#!/bin/bash\necho "$1" >> "$STATE/sleeps"\n')):
            path = os.path.join(bin_dir, tool)
            with open(path, 'w') as f:
                f.write(body)
            os.chmod(path, 0o755)
        etc = os.path.join(state, 'etc')
        os.makedirs(os.path.join(etc, 'sources.list.d'))
        for name, text in ({'sources.list': SOURCES} if sources is None else sources).items():
            with open(os.path.join(etc, name), 'w') as f:
                f.write(text)
        self.resolv_path = os.path.join(state, 'resolv.conf')
        with open(self.resolv_path, 'w') as f:
            f.write(resolv)
        self.state = state
        self.env = dict(os.environ, PATH=bin_dir + os.pathsep + os.environ['PATH'], STATE=state, APT_ETC=etc,
                        RESOLV_CONF=self.resolv_path)
        return etc

    def read(self, what):
        try:
            with open(os.path.join(self.state, what)) as f:
                return f.read().split('\n')[:-1]
        except OSError:
            return []

    def resolv(self):
        with open(self.resolv_path) as f:
            return f.read()


class AptRetry(Machine):
    def run_loop(self, name, fails, cache_hit, dns='up', sources=None):
        etc = self.machine(sources)
        env = dict(self.env, FAILS=str(fails), CACHE_HIT=cache_hit, BUILD_PKGS='gcc make', DNS=dns)
        p = subprocess.run(['bash', '-e', '-o', 'pipefail', '-c', loop(name)], env=env,
                           stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
        self.output = p.stdout.decode('utf-8', 'replace')
        with open(os.path.join(etc, 'sources.list')) as f:
            self.sources = f.read()
        return p.returncode, self.read('calls'), self.read('sleeps')

    def test_every_install_step_has_the_loop(self):
        for name in FILES:
            self.assertIsNotNone(loop(name), name)

    @POSIX
    def test_a_first_pass_that_fails_runs_again_after_an_update(self):
        for name in FILES:
            status, calls, sleeps = self.run_loop(name, 1, 'true')
            self.assertEqual(status, 0, name)
            # on a cache hit the first pass does not update; the second does
            self.assertEqual([c.split()[2] for c in calls], ['install', 'update', 'install'], name)
            self.assertEqual(sleeps, ['30'], name)
            # the second pass takes the security pocket from the archive
            self.assertNotIn('security.ubuntu.com', self.sources, name)
            self.assertIn('http://archive.ubuntu.com/ubuntu/ jammy-security main', self.sources, name)
            # a failed install is not a reason to change the name servers
            self.assertEqual(self.resolv(), RESOLV, name)

    @POSIX
    def test_without_the_cache_each_pass_updates_first(self):
        status, calls, sleeps = self.run_loop('web.yml', 2, '')
        self.assertEqual(status, 0)
        self.assertEqual([c.split()[2] for c in calls], ['update', 'install'] * 3)
        self.assertEqual(sleeps, ['30', '60'])

    @POSIX
    def test_three_failures_fail_the_step(self):
        status, calls, sleeps = self.run_loop('web.yml', 3, 'true')
        self.assertNotEqual(status, 0)
        self.assertEqual(len([c for c in calls if ' install ' in ' %s ' % c]), 3)

    @POSIX
    def test_a_pass_that_works_installs_once(self):
        status, calls, sleeps = self.run_loop('build-linux.yml', 0, '')
        self.assertEqual(status, 0)
        self.assertEqual([c.split()[2] for c in calls], ['update', 'install'])
        self.assertEqual(sleeps, [])
        self.assertEqual(self.sources, SOURCES)  # a first pass that works changes nothing
        self.assertEqual(self.resolv(), RESOLV)

    @POSIX
    def test_public_name_servers_follow_the_containers_own_when_the_archive_does_not_resolve(self):
        for name in FILES:
            status, calls, sleeps = self.run_loop(name, 0, '', dns='down')
            self.assertEqual(status, 0, name)
            # asked before the first apt-get, so the first pass already works
            self.assertEqual(self.read('lookups')[0], 'ahostsv4 archive.ubuntu.com', name)
            self.assertEqual([c.split()[2] for c in calls], ['update', 'install'], name)
            self.assertEqual(sleeps, [], name)
            # the container's own lines stay as they were, and first
            self.assertTrue(self.resolv().startswith(RESOLV), name)
            self.assertEqual(name_servers(self.resolv()), ['127.0.0.11'] + PUBLIC, name)
            self.assertIn('::warning::archive.ubuntu.com does not resolve', self.output, name)
            self.assertEqual(self.sources, SOURCES, name)

    @POSIX
    def test_the_name_servers_are_added_once_over_three_passes(self):
        for name in FILES:
            status, calls, sleeps = self.run_loop(name, 2, '', dns='down')
            self.assertEqual(status, 0, name)
            self.assertEqual(name_servers(self.resolv()), ['127.0.0.11'] + PUBLIC, name)
            # and the later passes ask for nothing: one lookup in all
            self.assertEqual(self.read('lookups'), ['ahostsv4 archive.ubuntu.com'], name)

    @POSIX
    def test_the_arm64_containers_server_is_the_one_asked(self):
        ports = {'sources.list': '# deb-src http://archive.ubuntu.com/ubuntu/ focal main\n'
                                 'deb http://ports.ubuntu.com/ubuntu-ports/ focal main restricted\n'}
        for name in FILES:
            status, calls, sleeps = self.run_loop(name, 0, 'true', dns='down', sources=ports)
            self.assertEqual(status, 0, name)
            self.assertEqual(self.read('lookups')[0], 'ahostsv4 ports.ubuntu.com', name)
            self.assertEqual(name_servers(self.resolv()), ['127.0.0.11'] + PUBLIC, name)


